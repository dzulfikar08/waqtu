// Generates apps/apple/waqtuTests/ImsakiyahFixtures.swift from @waqtu/core, so the Swift
// imsakiyah port (apps/apple/waqtu-sync/Imsakiyah.swift) is tested against the mobile app's
// own numbers (packages/core/src/ramadhan.ts: hijriMonthStart, hijriMonthLength,
// currentOrNextRamadhan, imsakiyahTable).
//
// Usage (repo root): bun apps/apple/scripts/imsakiyah-fixtures.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  currentOrNextRamadhan,
  hijriMonthLength,
  hijriMonthStart,
  imsakiyahTable,
  type CivilDate,
  type MethodId,
  type PrayerName,
} from "../../../packages/core/src/index.ts";

const OUT = fileURLToPath(new URL("../waqtuTests/ImsakiyahFixtures.swift", import.meta.url));

/** Core method id -> app method id (as stored in AppSettings.calculationMethod). */
const APP_METHOD: Partial<Record<MethodId, string>> = {
  kemenag: "kemenag",
  mwl: "muslimWorldLeague",
};

interface Case {
  id: string;
  latitude: number;
  longitude: number;
  timeZone: string;
  method: MethodId;
  hijriYear: number;
  hijriOffset: number;
  imsakMinutes?: number;
}

const JAKARTA = { latitude: -6.2088, longitude: 106.8456, timeZone: "Asia/Jakarta" };
const MALANG = { latitude: -7.9797, longitude: 112.6304, timeZone: "Asia/Jakarta" };
const LONDON = { latitude: 51.5074, longitude: -0.1278, timeZone: "Europe/London" };
// UTC+14 at longitude -157: adhan's solar day is the previous civil day there (core's dayShift).
const KIRITIMATI = { latitude: 1.8721, longitude: -157.4278, timeZone: "Pacific/Kiritimati" };

const CASES: Case[] = [
  { id: "jakarta-kemenag-1447", ...JAKARTA, method: "kemenag", hijriYear: 1447, hijriOffset: 0 },
  {
    id: "jakarta-kemenag-1447-lag",
    ...JAKARTA,
    method: "kemenag",
    hijriYear: 1447,
    hijriOffset: -1,
  },
  {
    id: "jakarta-kemenag-1447-imsak15",
    ...JAKARTA,
    method: "kemenag",
    hijriYear: 1447,
    hijriOffset: 1,
    imsakMinutes: 15,
  },
  { id: "malang-kemenag-1448", ...MALANG, method: "kemenag", hijriYear: 1448, hijriOffset: 0 },
  { id: "london-mwl-1447", ...LONDON, method: "mwl", hijriYear: 1447, hijriOffset: 0 },
  { id: "kiritimati-mwl-1447", ...KIRITIMATI, method: "mwl", hijriYear: 1447, hijriOffset: 0 },
];

const MONTHS: [year: number, month: number][] = [
  [1446, 9],
  [1447, 1],
  [1447, 9],
  [1447, 10],
  [1447, 12],
  [1448, 9],
  [1449, 9],
];
const MONTH_OFFSETS = [-1, 0, 1];

const SPAN_DATES = [
  "2025-12-31",
  "2026-02-18",
  "2026-02-19",
  "2026-03-19",
  "2026-03-20",
  "2026-07-01",
  "2027-02-08",
];
const SPAN_OFFSETS = [-1, 0];

const PRAYERS: PrayerName[] = ["imsak", "fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"];

const ymd = (d: CivilDate) =>
  `${d.year}-${String(d.month).padStart(2, "0")}-${String(d.day).padStart(2, "0")}`;
const parse = (s: string): CivilDate => {
  const [year, month, day] = s.split("-").map(Number);
  return { year, month, day };
};

const lines: string[] = [];
const out = (s = "") => lines.push(s);

out("//");
out("//  ImsakiyahFixtures.swift");
out("//  waqtuTests");
out("//");
out("//  GENERATED by apps/apple/scripts/imsakiyah-fixtures.ts from @waqtu/core; do not edit.");
out("//  Regenerate (repo root): bun apps/apple/scripts/imsakiyah-fixtures.ts");
out("//");
out();
out(
  '/// One `imsakiyahTable` row from core: local "HH:mm" per prayer, nil when it does not occur.',
);
out("struct ImsakiyahFixtureRow {");
out("    let hijriDay: Int");
out("    let date: String");
out("    let local: [String?]");
out();
out("    init(_ hijriDay: Int, _ date: String, _ local: String?...) {");
out("        self.hijriDay = hijriDay");
out("        self.date = date");
out("        self.local = local");
out("    }");
out("}");
out();
out("/// A full core imsakiyah table for one location / method / Hijri year / offset.");
out("struct ImsakiyahFixtureCase {");
out("    let id: String");
out("    let latitude: Double");
out("    let longitude: Double");
out("    let timeZone: String");
out("    /// App method id (`PrayerMethodParameters.base(for:)`).");
out("    let method: String");
out("    let hijriYear: Int");
out("    let hijriOffset: Int");
out("    let imsakMinutes: Int");
out("    let start: String");
out("    let length: Int");
out("    let rows: [ImsakiyahFixtureRow]");
out("}");
out();
out("/// `hijriMonthStart` / `hijriMonthLength` from core.");
out("struct HijriMonthFixture {");
out("    let year: Int");
out("    let month: Int");
out("    let offset: Int");
out("    let start: String");
out("    let length: Int");
out("}");
out();
out("/// `currentOrNextRamadhan` from core.");
out("struct RamadhanSpanFixture {");
out("    let date: String");
out("    let offset: Int");
out("    let hijriYear: Int");
out("    let start: String");
out("    let end: String");
out("    let eid: String");
out("}");
out();
out("enum ImsakiyahFixtures {");
out(`    /// Column order of \`ImsakiyahFixtureRow.local\`.`);
out(`    static let prayers: [String] = [${PRAYERS.map((p) => JSON.stringify(p)).join(", ")}]`);
out();
out("    static let months: [HijriMonthFixture] = [");
for (const [year, month] of MONTHS) {
  for (const offset of MONTH_OFFSETS) {
    const start = ymd(hijriMonthStart(year, month, offset));
    const length = hijriMonthLength(year, month, offset);
    out(
      `        HijriMonthFixture(year: ${year}, month: ${month}, offset: ${offset}, start: "${start}", length: ${length}),`,
    );
  }
}
out("    ]");
out();
out("    static let ramadhanSpans: [RamadhanSpanFixture] = [");
for (const date of SPAN_DATES) {
  for (const offset of SPAN_OFFSETS) {
    const s = currentOrNextRamadhan(parse(date), offset);
    out(
      `        RamadhanSpanFixture(date: "${date}", offset: ${offset}, hijriYear: ${s.hijriYear}, start: "${ymd(s.start)}", end: "${ymd(s.end)}", eid: "${ymd(s.eid)}"),`,
    );
  }
}
out("    ]");
out();
out("    static let cases: [ImsakiyahFixtureCase] = [");
for (const c of CASES) {
  const appMethod = APP_METHOD[c.method];
  if (!appMethod) throw new Error(`No app method id for ${c.method}`);
  const imsakMinutes = c.imsakMinutes ?? 10;
  const rows = imsakiyahTable({
    latitude: c.latitude,
    longitude: c.longitude,
    timeZone: c.timeZone,
    method: c.method,
    hijriYear: c.hijriYear,
    hijriOffset: c.hijriOffset,
    imsakMinutes,
  });
  out("        ImsakiyahFixtureCase(");
  out(`            id: "${c.id}",`);
  out(`            latitude: ${c.latitude},`);
  out(`            longitude: ${c.longitude},`);
  out(`            timeZone: "${c.timeZone}",`);
  out(`            method: "${appMethod}",`);
  out(`            hijriYear: ${c.hijriYear},`);
  out(`            hijriOffset: ${c.hijriOffset},`);
  out(`            imsakMinutes: ${imsakMinutes},`);
  out(`            start: "${ymd(rows[0].date)}",`);
  out(`            length: ${rows.length},`);
  out("            rows: [");
  for (const r of rows) {
    const local = PRAYERS.map((p) =>
      r.local[p] === null ? "nil" : JSON.stringify(r.local[p]),
    ).join(", ");
    out(`                ImsakiyahFixtureRow(${r.hijriDay}, "${ymd(r.date)}", ${local}),`);
  }
  out("            ]");
  out("        ),");
}
out("    ]");
out("}");

writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`wrote ${OUT}`);
