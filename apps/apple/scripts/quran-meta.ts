/**
 * Writes apps/apple/waqtu-sync/Modules/Hafalan/QuranMeta.swift from @waqtu/core's Tanzil metadata
 * (packages/core/src/quran-data.ts): surah names and ayah counts, and the first ayah of each juz
 * and mushaf page. waqtuTests compares the Swift file with quran-data.ts, so rerun this after the
 * metadata changes:
 *
 *   bun apps/apple/scripts/quran-meta.ts
 */
import { JUZ_START, PAGE_START, SURAHS } from "../../../packages/core/src/quran-data";

const out = new URL("../waqtu-sync/Modules/Hafalan/QuranMeta.swift", import.meta.url);

const ints = (list: readonly number[]) => {
  const lines: string[] = [];
  for (let i = 0; i < list.length; i += 16)
    lines.push(`        ${list.slice(i, i + 16).join(", ")},`);
  return lines.join("\n");
};

const swift = `//
//  QuranMeta.swift
//  waqtu
//
//  Generated by apps/apple/scripts/quran-meta.ts from packages/core/src/quran-data.ts. Do not edit.
//  Tanzil Quran Metadata (ver 1.0), Copyright (C) 2008-2009 Tanzil.info. License: Creative Commons
//  Attribution 3.0. https://tanzil.net. Indonesian names follow the Kemenag transliteration.
//

struct SurahInfo: Equatable {
    let arabic: String
    let id: String
    let en: String
    let ayahs: Int
}

enum QuranMeta {
    /// The 114 surahs in mushaf order.
    static let surahs: [SurahInfo] = [
${SURAHS.map((s) => `        SurahInfo(arabic: ${JSON.stringify(s.arabic)}, id: ${JSON.stringify(s.id)}, en: ${JSON.stringify(s.en)}, ayahs: ${s.ayahs}),`).join("\n")}
    ]

    /// Global 0-based index of the first ayah of each of the 30 juz.
    static let juzStart: [Int] = [
${ints(JUZ_START)}
    ]

    /// Global 0-based index of the first ayah of each of the 604 pages of the Madinah mushaf.
    static let pageStart: [Int] = [
${ints(PAGE_START)}
    ]
}
`;

await Bun.write(out, swift);
console.log(`wrote ${out.pathname}`);
