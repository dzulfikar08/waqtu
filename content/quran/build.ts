const NOTICE =
  "Tanzil Quran Text (Uthmani, Version 1.1). Copyright (C) 2007-2026 Tanzil Project. License: Creative Commons Attribution 3.0. Verbatim copy: changing the text is not allowed. Source: https://tanzil.net. Full terms: content/quran/README.md.";

const root = new URL("./", import.meta.url).pathname;
const metaPath = process.argv[2];
if (!metaPath) throw new Error("usage: bun content/quran/build.ts <quran-data.js>");

const QuranData = new Function(`${readFileSync(metaPath, "utf8")}; return QuranData;`)() as {
  Sura: [number, number, number, number, string, string, string, string][];
  Juz: [number, number][];
  Page: [number, number][];
};

const lines = readFileSync(`${root}quran-uthmani-1.1.txt`, "utf8")
  .split("\n")
  .filter((l) => /^\d/.test(l));
const surahs: string[][] = Array.from({ length: 114 }, () => []);
for (const line of lines) {
  const [s, a, text] = line.split("|");
  const list = surahs[Number(s) - 1];
  if (Number(a) !== list.length + 1) throw new Error(`Out of order ayah ${s}:${a}`);
  list.push(text);
}

const info = QuranData.Sura.slice(1, 115);
const offsets: number[] = [];
let total = 0;
for (const [i, list] of surahs.entries()) {
  if (list.length !== info[i][1]) throw new Error(`Surah ${i + 1}: ayah count mismatch`);
  offsets.push(total);
  total += list.length;
}
if (total !== 6236) throw new Error(`Expected 6236 ayahs, got ${total}`);
const index = ([s, a]: [number, number]) => offsets[s - 1] + a - 1;

mkdirSync(`${root}surah`, { recursive: true });
for (const [i, ayahs] of surahs.entries()) {
  const file = `${root}surah/${String(i + 1).padStart(3, "0")}.json`;
  writeFileSync(file, `${JSON.stringify({ notice: NOTICE, surah: i + 1, ayahs })}\n`);
}

const words = surahs.flatMap((list, i) =>
  list.map((text, a) => quranWords(splitBismillah(i + 1, a + 1, text).text).length),
);
const juz = QuranData.Juz.slice(1, 31).map(index);
const pages = QuranData.Page.slice(1, 605).map(index);
if (juz.length !== 30 || pages.length !== 604) throw new Error("Unexpected juz/page count");

const surahTable = info.map(([, ayahs, , , arabic, , en], i) => ({
  arabic,
  id: SURAH_IDS[i],
  en,
  ayahs,
}));

const out = `// Generated by content/quran/build.ts from Tanzil's Quran metadata (ver 1.0).
// Copyright (C) 2008-2009 Tanzil.info. License: Creative Commons Attribution 3.0. https://tanzil.net
// Indonesian names follow the Kemenag transliteration; English names are Tanzil's. Do not edit by hand.

export interface SurahInfo {
  arabic: string;
  id: string;
  en: string;
  ayahs: number;
}

/** The 114 surahs in mushaf order. */
export const SURAHS: readonly SurahInfo[] = ${JSON.stringify(surahTable)};

/** Global 0-based index of the first ayah of each juz (30) and of each page of the Madinah mushaf (604). */
export const JUZ_START: readonly number[] = ${JSON.stringify(juz)};
export const PAGE_START: readonly number[] = ${JSON.stringify(pages)};

/**
 * Words per ayah by global index (6236), not counting the Bismillah Tanzil prepends to ayah 1.
 * Weights the half-page units of a hafalan plan.
 */
export const AYAH_WORDS: readonly number[] = ${JSON.stringify(words)};
`;
writeFileSync(`${root}../../packages/core/src/quran-data.ts`, out);

